function unique(values) {
  return [...new Set(values)];
}

function makeNodes() {
  const flatNodes = [];
  const relationSeed = {};

  for (const cluster of clusters) {
    const ids = cluster.items.map((item) => item.id);
    const hubId = ids[0];

    ids.forEach((id, index) => {
      const prevId = ids[(index - 1 + ids.length) % ids.length];
      const nextId = ids[(index + 1) % ids.length];
      relationSeed[id] = unique([prevId, nextId, ...(id === hubId ? ids.filter((target) => target !== id) : [hubId])]);
    });

    flatNodes.push(
      ...cluster.items.map((item) => ({
        ...item,
        domain: cluster.label,
        theme: cluster.theme,
      }))
    );
  }

  for (const [id, links] of Object.entries(crossLinks)) {
    relationSeed[id] = unique([...(relationSeed[id] ?? []), ...links]);
  }

  return flatNodes.map((node) => ({
    ...node,
    english: bilingualMeta[node.id]?.english ?? "",
    chinese: bilingualMeta[node.id]?.chinese ?? "",
    related: unique((relationSeed[node.id] ?? []).filter((target) => target !== node.id)),
  }));
}

